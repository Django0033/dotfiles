  if (!fs2.existsSync(versionDir)) fs2.mkdirSync(versionDir, { recursive: true });
  const beforeRaw = typeof beforeRawOverride === "string" ? beforeRawOverride : fs2.readFileSync(profilePath, "utf-8").toString();
  const createdAt = (/* @__PURE__ */ new Date()).toISOString();
  const versionFile = `${sanitizeTimestampForFileName(createdAt)}-${Math.random().toString(36).slice(2, 8)}.json`;
  const id2 = `${profileFile}/${versionFile}`;
