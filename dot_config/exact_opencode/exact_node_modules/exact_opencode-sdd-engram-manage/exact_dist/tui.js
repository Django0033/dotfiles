function atomicWriteFile(filePath, content) {
  const tmpPath = `${filePath}.tmp-${randomBytes(4).toString("hex")}`;
  let tempFd;
  let dirFd;
  let renameCompleted = false;
  try {
    fs2.writeFileSync(tmpPath, content);
    tempFd = fs2.openSync(tmpPath, "r+");
    try {
      fs2.fsyncSync(tempFd);
    } catch (e) {
      if (!hasErrorCode(e, "EPERM")) throw e;
      log3.warn(`atomicWriteFile: fsync skipped for temporary file ${tmpPath}`, e);
    }
    fs2.closeSync(tempFd);
    tempFd = void 0;
    fs2.renameSync(tmpPath, filePath);
    renameCompleted = true;
    dirFd = fs2.openSync(path2.dirname(filePath), "r");
    try {
      fs2.fsyncSync(dirFd);
    } catch (e) {
      if (!hasErrorCode(e, "EPERM")) throw e;
      log3.warn(`atomicWriteFile: directory fsync skipped for ${path2.dirname(filePath)}`, e);
    }
  } finally {
    if (typeof tempFd === "number") {
      fs2.closeSync(tempFd);
    }
    if (typeof dirFd === "number") {
      fs2.closeSync(dirFd);
    }
    if (!renameCompleted) {
      try {
        fs2.unlinkSync(tmpPath);
      } catch (e) {
        log3.warn(`atomicWriteFile: failed to remove temporary file ${tmpPath}`, e);
      }
    }
  }
}
